//go:build windows

package main

import (
	"fmt"
	"os"
	"os/exec"
	"syscall"
)

// restartWithSwap — Windows не даёт подменить (даже переименовать поверх)
// exe, который прямо сейчас выполняется как этот процесс: файл образа
// заблокирован загрузчиком, пока процесс жив. Поэтому подмена идёт отдельным
// detached-процессом, который сначала дожидается, пока этот процесс точно
// завершится, затем подменяет файл и запускает уже новую версию.
//
// Один `move` после одной паузы был недостаточно надёжен: свежескачанный
// .exe регулярно ещё секунду-другую держит захваченным штатный антивирус
// (реал-тайм проверка новых файлов) даже после того, как сам процесс уже
// вышел, и `move` падал молча — пользователь оставался со старой версией и
// висящим рядом ".new", которые приходилось разбирать руками. Цикл из
// нескольких попыток с паузой между ними ждёт ровно столько, сколько
// реально нужно, вместо одной ставки на секунду.
//
// Ретраи и `goto` — то, что переносится в отдельный .bat-файл, а не
// однострочник через `cmd /C "... & ... & ..."`: метки внутри одной такой
// командной строки ищутся ненадёжно, реальный .bat-файл читается построчно
// и с ними работает предсказуемо. `del "%~f0"` в конце — самоудаление уже
// отработавшего скрипта (Windows разрешает удалить файл, пока его же
// исполняет собственный интерпретатор), чтобы такие файлы не копились во
// временном каталоге при каждом обновлении.
func restartWithSwap(exe, staged string) error {
	// Пауза между попытками — через `ping`, а не `timeout`: у detached-
	// процесса без своей консоли (ровно наш случай — HideWindow, запущен из
	// GUI) `timeout` немедленно падает с "Input redirection is not
	// supported" вместо ожидания, и все 20 попыток стреляют одна за другой
	// почти мгновенно — той же секунды-другой, что обычно и нужна
	// антивирусу, они тогда не покрывают. `ping -n 2 127.0.0.1` ждёт ~1с и
	// консоли не требует вовсе.
	script := fmt.Sprintf(`@echo off
for /L %%%%i in (1,1,20) do (
  move /Y "%s" "%s" >nul 2>&1 && goto :done
  ping -n 2 127.0.0.1 >nul
)
:done
start "" "%s"
del "%%~f0"
`, staged, exe, exe)

	f, err := os.CreateTemp("", "hkc-update-*.bat")
	if err != nil {
		return err
	}
	if _, err := f.WriteString(script); err != nil {
		f.Close()
		os.Remove(f.Name())
		return err
	}
	if err := f.Close(); err != nil {
		os.Remove(f.Name())
		return err
	}

	cmd := exec.Command("cmd", "/C", f.Name())
	cmd.SysProcAttr = &syscall.SysProcAttr{HideWindow: true}
	return cmd.Start()
}
