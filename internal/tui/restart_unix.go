//go:build unix

package tui

import (
	"os"
	"syscall"
)

// RestartSelf заменяет ОБРАЗ текущего процесса новым бинарником, а не
// порождает дочерний и не убивает себя.
//
// Разница здесь не косметическая. Прежний вариант (exec.Command + Start +
// os.Exit) для TUI не работает в принципе: как только родитель завершается,
// shell забирает управляющий терминал обратно себе, а только что запущенный
// hkc оказывается фоновым процессом. Первая же попытка войти в raw-режим
// (это делает Bubble Tea на старте экрана проверок) упирается в терминал,
// который процессу больше не принадлежит, и падает с
// "error entering raw mode: input/output error" — ровно то, что вылезало
// сразу после успешного самообновления.
//
// syscall.Exec такого не создаёт: PID, группа процессов, сессия и
// управляющий терминал остаются теми же самыми — меняется только код,
// который в этом процессе исполняется. Функция не возвращается вовсе, если
// всё прошло успешно.
//
// Вызывать её нужно ПОСЛЕ того, как Bubble Tea вернул терминал в обычный
// режим (см. runUpdateScreen в cmd/hkc/main.go): образ меняется мгновенно,
// и отложенное восстановление терминала выполнить будет уже некому — иначе
// новый процесс наследует alt-screen и raw-режим от старого.
func RestartSelf() error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	return syscall.Exec(exe, []string{exe}, os.Environ())
}
